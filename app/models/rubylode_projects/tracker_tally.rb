module RubylodeProjects
  # Open and closed issues of one tracker. "Done" is the closed share, not Redmine's done ratio.
  TrackerTally = Data.define(:tracker, :open_count, :closed_count) do
    def total_count = open_count + closed_count

    def done_percentage = Percentage.of(closed_count, total_count)
  end
end
