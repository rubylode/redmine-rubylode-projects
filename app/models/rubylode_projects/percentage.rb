module RubylodeProjects
  module Percentage
    # Whole percent, rounded down: 100 means all of them, never "999 of 1000".
    def self.of(part, whole)
      return 0 if whole.to_i <= 0

      part.to_i * 100 / whole.to_i
    end
  end
end
